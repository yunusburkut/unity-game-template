# PreToolUse guard (gamekit plugin) for the read-only agents: scout, bug-hunter, unity-reviewer, perf-auditor,
# clarity-reviewer, design-critic and the coop-multiplayer pack's net-auditor have Bash for git log/diff/show and grep
# only, and their prompt alone would keep them from changing the user's one working checkout or driving the Editor.
# Plugin agent frontmatter cannot carry hooks, so the rule lives here: inside one of those agents (the hook input's
# agent_type, "gamekit:scout" or "scout"), a git verb that changes state, a redirect/tee into a file outside %TEMP%, a
# gk-bridge request other than the read-only `gk-bridge fresh` (it sends nothing to Unity), or a Unity CLI verb other
# than status/list/logs/docs/help/--version is denied (the other gk-bridge requests and `unity command` drive the one
# Editor, one request at a time, and the reviewers run in parallel). The main session and the builder pass untouched.
# hooks/hooks.json runs this only for Bash commands that contain "git ", a ">", "tee ", "gk-bridge" or "unity " (`if`,
# generated by plugin\test-hooks.ps1 -Write), so other calls never start PowerShell; in the main session such a call
# costs one PowerShell start (about 0.3 s) and passes.
# Ceiling: a heuristic on the command text, like guard-unity-yaml: a script file that writes on its own, or a '>' inside
# a quoted grep pattern (denied: rephrase it), is not told apart. Fails open on unreadable input.
# Pure ASCII on purpose: Windows PowerShell 5.1 reads a BOM-less script as ANSI.
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$stdin = [Console]::OpenStandardInput()
$buffer = New-Object IO.MemoryStream
$stdin.CopyTo($buffer)
try {
    # A PowerShell pipe prepends a BOM; Claude Code sends raw UTF-8.
    $payload = [Text.Encoding]::UTF8.GetString($buffer.ToArray()).TrimStart([char]0xFEFF) | ConvertFrom-Json
} catch { exit 0 }

$agent = [string]$payload.agent_type
if ($agent -notmatch '^(?:[\w-]+:)?(scout|bug-hunter|unity-reviewer|perf-auditor|clarity-reviewer|design-critic|net-auditor)$') { exit 0 }
$name = $Matches[1]
$command = [string]$payload.tool_input.command

$gitVerbs = 'stash|checkout|reset|restore|clean|commit|add|rm|mv|push|rebase|merge|switch|branch|tag|cherry-pick|revert|am|apply|pull|fetch'
$why = $null
foreach ($m in [regex]::Matches($command, "(?:^|[\s;|&(])git(?:\s+(?:-[cC]\s+\S+|--[\w-]+(?:=\S+)?))*\s+($gitVerbs)\b([^;|&)]*)")) {
    $verb = $m.Groups[1].Value; $rest = $m.Groups[2].Value
    # The read-only forms of these verbs stay allowed.
    $readOnly = switch ($verb) {
        'stash'  { $rest -match '^\s+(list|show)\b' }
        'clean'  { $rest -match '(^|\s)(-n|--dry-run)\b' }
        'branch' { $rest -notmatch '(^|\s)(-[dDmMcCfu]|--delete|--move|--copy|--force|--set-upstream-to|--unset-upstream|--edit-description)\b' -and
                   ($rest -notmatch '(^|\s)[^-\s]' -or $rest -match '(^|\s)(-l|--list|--contains|--no-contains|--merged|--no-merged|--points-at)\b') }
        'tag'    { $rest -match '^\s*$|^\s+(-l|--list|-n\d*|--contains|--points-at|--merged|--no-merged|--sort)\b' }
        'apply'  { $rest -match '(^|\s)(--check|--stat|--numstat|--summary)\b' -and $rest -notmatch '(^|\s)--index\b' }
        default  { $false }
    }
    if (-not $readOnly) { $why = "git $verb changes the working tree, the index or the history"; break }
}
if (-not $why) {
    # gk-bridge and the Unity CLI at a command's start (after ;, |, &, (, bash/sh or VAR=value, with or without a path
    # or quotes); a quoted grep pattern that names them is not at a command's start and passes.
    foreach ($m in [regex]::Matches($command, '(?:^|[;|&(\n])\s*(?:\w+=\S*\s+)*(?:(?:bash|sh)\s+)?["'']?(?:[^\s"'';|&()]*[/\x5C])?(gk-bridge|unity(?:\.exe)?)["'']?(?=\s|$)(?:\s+(\S+))?')) {
        if ($m.Groups[1].Value -eq 'gk-bridge') { if ($m.Groups[2].Value -ne 'fresh') { $why = "gk-bridge $($m.Groups[2].Value) drives the Unity Editor (the main session runs it; only gk-bridge fresh is read-only)"; break }; continue }
        if ($m.Groups[2].Value -notmatch '^(|status|list|logs|docs|help|--help|-h|--version)$') { $why = "unity $($m.Groups[2].Value) drives the Unity Editor (the main session runs it)"; break }
    }
}
if (-not $why) {
    # Redirect targets (2>&1 and >&2 are not files) and tee targets: only /dev/null and %TEMP% are free.
    $targets = @([regex]::Matches($command, '(?<![<>=-])(?:\d|&)?>{1,2}\s*(?!&)([^\s;|&()<>]+)') | ForEach-Object { $_.Groups[1].Value }) +
        @([regex]::Matches($command, '(?:^|[\s;|&(])tee((?:\s+-\w+)*\s+[^;|&)]+)') | ForEach-Object { $_.Groups[1].Value -split '\s+' } | Where-Object { $_ -and $_ -notmatch '^-' })
    $temp = @([IO.Path]::GetTempPath().TrimEnd('\'), $env:TEMP, $env:TMP) | Where-Object { $_ } | ForEach-Object { ($_ -replace '\\', '/').TrimEnd('/') }
    foreach ($t in $targets) {
        $p = ($t.Trim('"', "'") -replace '\\', '/') -replace '^/([a-zA-Z])/', '$1:/'
        if ($p -match '^(/dev/(null|stderr|stdout)|\$null|nul)$' -or $p -match '^(/tmp|\$TEMP|\$TMP|\$TMPDIR|\$env:TEMP|%TEMP%)(/|$)') { continue }
        if (@($temp | Where-Object { $p.StartsWith($_ + '/', [StringComparison]::OrdinalIgnoreCase) }).Count) { continue }
        $why = "it writes $t"; break
    }
}
if (-not $why) { exit 0 }

@{ hookSpecificOutput = @{
    hookEventName = 'PreToolUse'
    permissionDecision = 'deny'
    permissionDecisionReason = "$name is read-only and $why. Read with git log/diff/show/status, grep and cat; put scratch output under %TEMP% or /tmp; a change belongs in the report as a proposal for the main conversation."
} } | ConvertTo-Json -Compress -Depth 4
exit 0
